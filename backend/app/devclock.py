"""Перевод меток времени прибора в шкалу часов хоста.

Прибор ставит принятому кадру 32-битную метку в микросекундах (переполнение каждые
~71,6 мин), а кадрам, которые шлём мы, метку даёт хост. Чтобы Rx и Tx шли по одной
шкале (и запись не «прыгала» при переподключении), метка прибора переводится во время
хоста: `время = метка + смещение`, где смещение — наименьшее наблюдённое
(время получения − метка), то есть метка плюс минимальная задержка доставки.
Смещение сразу уменьшается, если кадр пришёл быстрее прежнего минимума, и медленно
растёт (не быстрее DRIFT), если кварц прибора отстаёт от часов хоста. Рост — только по
минимуму окна из нескольких кадров длиной не меньше секунды: кадр, задержанный доставкой
(первый после долгой тишины), смещение не поднимает, иначе следующий кадр вернул бы его
вниз и время пошло бы назад. Поэтому время кадра никогда не позже момента, когда хост
его получил, а промежутки между кадрами — это промежутки по меткам прибора.

Если смещение разошлось больше чем на RESYNC_S (сон компьютера, прибор перезапустился,
не сбросив соединение), шкала переякоривается по времени прихода.

Переполнение счётчика разворачивается по часам хоста: из всех `метка + k·2³²` берётся
ближайшая к ожидаемой (прошлая метка + сколько прошло на хосте), поэтому паузы в шине
любой длины развёртку не путают."""
from __future__ import annotations

WRAP_S = 2**32 / 1e6     # период переполнения счётчика прибора, с
DRIFT = 2e-4             # допустимый уход кварца прибора относительно хоста, с/с (200 ppm)
WINDOW_S = 1.0           # окно (по меткам прибора), по минимуму которого смещение растёт
RESYNC_S = 30.0          # расхождение больше — разрыв шкалы, а не задержка доставки


class DeviceClock:
    def __init__(self) -> None:
        self._d_last: float | None = None   # развёрнутая метка последнего кадра, с
        self._h_last = 0.0                  # время хоста, когда он пришёл
        self._offset: float | None = None
        self._win: list[float] | None = None  # [начало окна по прибору, минимум смещения в нём]
        self._win_n = 0

    def unwrap(self, raw_us: int, host_now: float) -> float:
        """Развёрнутая метка прибора в секундах."""
        raw = (int(raw_us) & 0xFFFFFFFF) / 1e6
        if self._d_last is None:
            return raw
        expected = self._d_last + (host_now - self._h_last)
        k = round((expected - raw) / WRAP_S)
        return raw + k * WRAP_S

    def to_host(self, raw_us: int, host_now: float) -> float:
        """Метка прибора (мкс, 32 бита) → время хоста, с."""
        d = self.unwrap(raw_us, host_now)
        off = host_now - d
        if self._offset is None or off <= self._offset or off - self._offset > RESYNC_S:
            self._offset = off                      # быстрее прежнего минимума — или разрыв шкалы
            self._win, self._win_n = None, 0
        elif self._win is None:
            self._win, self._win_n = [d, off], 1
        else:
            w = self._win
            w[1] = min(w[1], off)
            self._win_n += 1
            if d - w[0] >= WINDOW_S and self._win_n >= 2:
                self._offset = min(w[1], self._offset + (d - w[0]) * DRIFT)
                self._win, self._win_n = None, 0
        self._d_last, self._h_last = d, host_now
        return d + self._offset
